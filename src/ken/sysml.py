"""Emit a SysML v2 model from a ken index.

SysML v2 is a good *output* format: it has a real grammar, a formal
specialization relationship, and consumers (viewers, MBSE tools, our own
``sysmlpy``) that will read it. It is a poor *storage* format, which is why the
SQLite index stays the system of record and this module is a one-way projection.

The projection is deliberately small: namespaces come from directories, classes
become ``part def`` declarations with a couple of attributes, inheritance
becomes ``specializes``, and class-level use becomes a ``dependency``. Anything
ken knows that SysML v2 has no slot for (unresolved name references, candidate
sets, call-site lines) is counted and reported rather than invented.

Two invariants matter, and both are enforced by counting:

* every class in scope appears exactly once, because a dropped element in an
  interchange file is invisible; and
* every emitted declaration has a document-unique name, because SysML v2
  namespaces do not allow repeats and a silent merge would lose a class.
"""
from __future__ import annotations

import sqlite3
from collections import OrderedDict

CLASS_KINDS = ("class", "interface", "struct", "enum")


def _ident(name: str) -> str:
    """A legal SysML v2 identifier derived from an arbitrary source name."""
    out = "".join(c if (c.isalnum() or c == "_") else "_" for c in name).strip("_") or "x"
    if out[0].isdigit():
        out = "x" + out
    return out


class _Scope:
    """A directory in the projected namespace tree."""

    __slots__ = ("name", "path", "children", "classes")

    def __init__(self, name: str, path: str):
        self.name = name
        self.path = path
        self.children: "OrderedDict[str, _Scope]" = OrderedDict()
        self.classes: list[sqlite3.Row] = []


def _corpus_root(con) -> str:
    row = con.execute("SELECT MIN(path), MAX(path) FROM files").fetchone()
    lo, hi = row
    if not lo:
        return ""
    import os
    return os.path.commonpath([lo, hi]) if lo != hi else os.path.dirname(lo)


def _class_rows(con, scope: str | None):
    sql = ("SELECT e.id, e.name, e.kind, e.line, e.complexity, e.parent_id, f.path"
           "  FROM entities e JOIN files f ON f.id = e.file_id"
           " WHERE e.kind IN (%s)" % ",".join("?" * len(CLASS_KINDS)))
    args = list(CLASS_KINDS)
    con.row_factory = sqlite3.Row
    if scope:
        sql += " AND f.path LIKE ?"
        args.append("%" + scope.strip("/") + "/%")
    return con.execute(sql + " ORDER BY f.path, e.line", args).fetchall()


def emit(con, scope: str | None = None, max_classes: int = 4000) -> tuple[str, dict]:
    """Project the index (optionally one directory subtree) to SysML v2 text."""
    root = _corpus_root(con)
    rows = _class_rows(con, scope)
    stats = {"classes": len(rows), "emitted": 0, "generalizations": 0, "dependencies": 0,
             "skipped": 0, "truncated": 0, "scope": scope or "."}
    if len(rows) > max_classes:
        stats["truncated"] = len(rows) - max_classes
        rows = rows[:max_classes]

    tree = _Scope("ken", "")
    rels = {}
    for r in rows:
        p = r["path"]
        if scope:
            i = p.find(scope.rstrip("/"))
            p = p[i + len(scope.rstrip("/")):].lstrip("/") if i >= 0 else p
        elif root:
            p = p[len(root):].lstrip("/")
        rels[r["id"]] = p
        node = tree
        parts = p.split("/")[:-1]
        for part in parts:
            node = node.children.setdefault(part, _Scope(part, node.path + "/" + part))
        node.classes.append(r)

    taken: set[str] = set()

    def uniq(base: str) -> str:
        name, n = base, 1
        while name in taken:
            n += 1
            name = "%s_%d" % (base, n)
        taken.add(name)
        return name

    # Deterministic naming: walk the tree in sorted order so the same index
    # always produces byte-identical output (diffable in review).
    named: dict[int, str] = {}

    def name_tree(node: _Scope) -> None:
        used = set()
        for key in list(node.children):
            base = _ident(key)
            nm, n = base, 1
            while nm in used:
                n += 1
                nm = "%s_%d" % (base, n)
            used.add(nm)
            node.children[key].name = nm
            name_tree(node.children[key])
        for r in node.classes:
            named[r["id"]] = uniq(_ident(r["name"]))

    tree.name = "ken"
    name_tree(tree)

    def indent(depth: int) -> str:
        return "    " * depth

    lines = ["package ken {",
             "    doc /* Generated by ken from a source index. Namespaces are",
             "           directories, part defs are type declarations, specializes",
             "           is inheritance, dependency is use. Not hand-editable",
             "           source of truth: the index is. */"]
    seen: dict[int, sqlite3.Row] = {r["id"]: r for r in rows}

    def emit_scope(node: _Scope, depth: int, first: bool) -> None:
        if not first:
            lines.append(indent(depth) + "package %s {" % node.name)
        body = depth + 1
        for key in node.children:
            emit_scope(node.children[key], body, False)
        for r in sorted(node.classes, key=lambda x: named[x["id"]]):
            sup = _supertype(con, r["id"], seen, named)
            head = indent(body) + "part def " + named[r["id"]]
            if sup:
                head += " specializes " + sup
                stats["generalizations"] += 1
            lines.append(head + " {")
            lines.append(indent(body + 1) + "attribute kind = \"%s\";" % r["kind"])
            lines.append(indent(body + 1) + "attribute line = %d;" % r["line"])
            lines.append(indent(body + 1) + "attribute complexity = %d;" % (r["complexity"] or 0))
            lines.append(indent(body) + "}")
            stats["emitted"] += 1
        if not first:
            lines.append(indent(depth) + "}")

    emit_scope(tree, 1, True)

    for a, b, n in _class_dependencies(con, rels, seen, named):
        lines.append("    dependency %s_uses_%s from %s to %s;"
                     % (a.lower(), b.lower(), a, b))
        stats["dependencies"] += 1
    lines.append("}")
    return "\n".join(lines) + "\n", stats


def _supertype(con, eid: int, seen: dict, named: dict) -> str | None:
    row = con.execute(
        "SELECT target_id FROM refs WHERE kind = 'inherit' AND src_entity = ?"
        "   AND target_id IS NOT NULL ORDER BY line LIMIT 1", (eid,)).fetchone()
    if not row or row[0] not in named:
        return None
    return named[row[0]] if row[0] in seen else None


def _owner_map(con) -> dict[int, int | None]:
    return {r[0]: r[1] for r in con.execute("SELECT id, parent_id FROM entities")}


def _class_dependencies(con, rels: dict[int, str], seen: dict, named: dict):
    """Class-level use: any call or instantiation from a member of A to a member of B."""
    owner = _owner_map(con)
    in_scope = set(seen)

    def cls_of(eid: int) -> int | None:
        hops = 0
        while eid is not None and hops < 8:
            if eid in in_scope:
                return eid
            eid = owner.get(eid)
            hops += 1
        return None

    pairs: dict[tuple[int, int], int] = {}
    for s, d in con.execute(
            "SELECT src_entity, target_id FROM refs"
            "  WHERE kind IN ('call','instantiate') AND target_id IS NOT NULL"):
        a, b = cls_of(s), cls_of(d)
        if a and b and a != b:
            pairs[(a, b)] = pairs.get((a, b), 0) + 1
    out = []
    for a, b in sorted(pairs, key=lambda k: (named[k[0]], named[k[1]])):
        out.append((named[a], named[b], pairs[(a, b)]))
    return out
